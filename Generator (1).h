#pragma once

namespace miit::algebra
{
    /**
     * @brief Абстрактный генератор целочисленных значений
     * @details Наследники задают конкретный алгоритм получения чисел:
     * случайный выбор, чтение из потока или постоянное значение.
     * Matrix::fill() работает только с этим интерфейсом, не зная,
     * откуда именно берутся элементы.
     */
    class Generator
    {
    public:
        /**
         * @brief Виртуальный деструктор
         * @details Обязателен для корректного удаления объекта через
         * указатель на базовый класс
         */
        virtual ~Generator() = default;

        /**
         * @brief Получить очередное целое число
         * @return Сгенерированное значение
         * @details Чисто виртуальный метод: каждый наследник обязан
         * реализовать свой способ генерации
         */
        virtual int generate() = 0;
    };
}
